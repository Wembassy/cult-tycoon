/**
 * MissionTemplates — Static data for external missions.
 *
 * Cultists can be sent on missions outside the compound for various rewards:
 *   - Heat reduction: lower the heat stat
 *   - PR generation: increase follower quality / reputation
 *   - Object acquisition: obtain decor/ornaments (generates heat)
 *   - Resource gathering: earn money and influence
 *
 * Each mission has a difficulty (1-10), duration (in-game hours),
 * min/max cultist count, and random events with skill-check choices.
 *
 * Refer to docs/gameplay-design-reference.md §10 Missions System for design details.
 */

export type MissionType =
  | 'heat_reduction'
  | 'pr_generation'
  | 'object_acquisition'
  | 'resource_gathering';

export interface MissionTemplate {
  id: string;
  name: string;
  type: MissionType;
  description: string;
  /** Duration in in-game hours */
  duration: number;
  /** Difficulty 1-10 */
  difficulty: number;
  rewards: {
    heatReduction?: number;
    prGain?: number;
    money?: number;
    influence?: number;
    /** Decor item ID from DecorItems data */
    decorItemId?: string;
  };
  /** Heat generated by running this mission */
  heatCost: number;
  /** Minimum cultists required to send */
  minCultists: number;
  /** Maximum cultists allowed */
  maxCultists: number;
  events: MissionEvent[];
}

export interface MissionEvent {
  id: string;
  text: string;
  choices: MissionChoice[];
}

export interface MissionChoice {
  label: string;
  skillCheck?: { skill: string; difficulty: number };
  outcomes: {
    success: {
      money?: number;
      influence?: number;
      prGain?: number;
      heatReduction?: number;
      decorItemId?: string;
      text: string;
    };
    failure: {
      money?: number;
      influence?: number;
      heatGain?: number;
      injuryChance?: number;
      text: string;
    };
  };
}

