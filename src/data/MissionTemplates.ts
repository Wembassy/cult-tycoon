// ─── Helper Functions ──────────────────────────────────────────

/**
 * Get a mission template by its ID.
 */
export function getMissionTemplate(id: string): MissionTemplate | undefined {
  return MISSION_TEMPLATES[id];
}

/**
 * Get all mission templates as an array.
 */
export function getAllMissionTemplates(): MissionTemplate[] {
  return Object.values(MISSION_TEMPLATES);
}

/**
 * Get all mission templates of a specific type.
 */
export function getMissionsByType(type: MissionType): MissionTemplate[] {
  return Object.values(MISSION_TEMPLATES).filter((m) => m.type === type);
}